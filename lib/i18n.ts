const DICT: Record<Locale, Record<Key, string>> = { en, de, es, fr, pt }

export function resolveLocale(hint?: string): Locale {
  const candidate = (
    hint ||
    (typeof navigator !== 'undefined' ? navigator.language : 'en') ||
    'en'
  )
    .split('-')[0]
    .toLowerCase()
  return (LOCALES as readonly string[]).includes(candidate) ? (candidate as Locale) : 'en'
}

export function translate(locale: Locale, key: Key, vars?: Record<string, string>): string {
  let out = DICT[locale][key] ?? DICT.en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace('{' + k + '}', v)
  return out
}

export function hostLocale(): Locale {
  let hint: string | undefined
  try {
    hint = getHostLanguage()
  } catch {
    hint = undefined
  }
  return resolveLocale(hint)
}
